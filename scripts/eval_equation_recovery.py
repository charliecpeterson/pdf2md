"""Score padded math-OCR candidates against the frozen equation-component corpus.

The recognizer outputs are preserved inputs, not regenerated by this check. The
evaluator verifies every source crop and implementation hash, then compares the
production-eligible replacements with the current selected equations.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path


_ROOT = Path(__file__).parent.parent
_DEFAULT_CORPUS = _ROOT / "tests" / "equation_recovery_corpus.json"
_EQUATION_SPEC = importlib.util.spec_from_file_location(
    "eval_equations", _ROOT / "scripts" / "eval_equations.py"
)
_EQUATIONS = importlib.util.module_from_spec(_EQUATION_SPEC)
assert _EQUATION_SPEC.loader is not None
_EQUATION_SPEC.loader.exec_module(_EQUATIONS)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _key(record: dict) -> tuple[str, int, str]:
    return record["source"], int(record["page"]), record["note"]


def _verified_path(item: dict) -> Path:
    path = _ROOT / item["path"]
    if not path.is_file():
        raise FileNotFoundError(path)
    if _sha256(path) != item["sha256"]:
        raise ValueError(f"artifact hash mismatch: {item['path']}")
    return path


def _geometry_evidence(item: dict, artifacts: dict, cache: dict[str, dict]) -> dict | None:
    artifact_name = item.get("provenance_artifact")
    if artifact_name is None:
        return None
    if artifact_name not in cache:
        provenance_path = _verified_path(artifacts[artifact_name])
        cache[artifact_name] = {
            "path": provenance_path,
            "document": json.loads(provenance_path.read_text()),
        }
    provenance = cache[artifact_name]
    document = provenance["document"]
    if Path(document["source_path"]).name != item["source"]:
        raise ValueError(f"candidate source mismatch: {item['source']}")
    block = next(
        (block for block in document["blocks"] if block["id"] == item["block_id"]),
        None,
    )
    if block is None:
        raise ValueError(f"candidate block missing: {item['block_id']}")
    crop_path = (provenance["path"].parent / block["extra"]["crop_path"]).resolve()
    if crop_path != (_ROOT / item["crop"]["path"]).resolve():
        raise ValueError(f"candidate crop does not match block: {item['block_id']}")
    if int(block["page"]) != int(item["page"]) or block.get("bbox") is None:
        raise ValueError(f"candidate page geometry mismatch: {item['block_id']}")
    return {
        "block_id": block["id"],
        "bbox": block["bbox"],
        "embedded_glyph_text": block["extra"].get("text_layer"),
        "embedded_glyph_ordered": block["extra"].get("ordered"),
        "crop_path_verified": True,
    }


def evaluate(corpus_path: Path) -> dict:
    corpus = json.loads(corpus_path.read_text())
    artifacts = corpus["artifacts"]
    labels_path = _verified_path(artifacts["labels"])
    baseline_path = _verified_path(artifacts["baseline_report"])
    _verified_path(artifacts["transcriber"])
    labels = json.loads(labels_path.read_text())
    baseline = json.loads(baseline_path.read_text())
    labels_by_key = {_key(label): label for label in labels}
    baseline_by_key = {_key(record): record for record in baseline["records"]}

    candidates = []
    production_by_key = {}
    provenance_cache = {}
    for item in corpus["candidates"]:
        _verified_path(item["crop"])
        key = _key(item)
        metrics = _EQUATIONS._candidate_metrics(item["latex"], labels_by_key[key])
        record = {
            "source": item["source"],
            "page": item["page"],
            "note": item["note"],
            "method": item["method"],
            "production_eligible": item["production_eligible"],
            "geometry": _geometry_evidence(item, artifacts, provenance_cache),
            "metrics": metrics,
        }
        candidates.append(record)
        if item["production_eligible"]:
            production_by_key[key] = item["latex"]

    production_records = []
    for label in labels:
        key = _key(label)
        baseline_record = baseline_by_key[key]
        latex = production_by_key.get(
            key, baseline_record["candidates"]["selected"]["latex"]
        )
        production_records.append(
            {
                "status": "checked",
                "candidates": {
                    "selected": _EQUATIONS._candidate_metrics(latex, label)
                },
            }
        )
    production = _EQUATIONS._aggregate(production_records, "selected")

    targeted = [
        record for record in baseline["records"]
        if not record["candidates"]["selected"]["full_exact"]
    ]
    baseline_exact = [
        record for record in baseline["records"]
        if record["candidates"]["selected"]["full_exact"]
    ]
    targeted_keys = {_key(record) for record in targeted}
    targeted_candidates = {
        _key(record): record
        for record in candidates
        if record["production_eligible"] and _key(record) in targeted_keys
    }
    controls = [
        record for record in candidates
        if baseline_by_key[_key(record)]["candidates"]["selected"]["full_exact"]
    ]
    diagnostic = next(
        record for record in candidates if not record["production_eligible"]
    )
    return {
        "schema_version": 1,
        "method": "padded_surya_equation_recovery",
        "corpus_path": corpus_path.relative_to(_ROOT).as_posix(),
        "corpus_sha256": _sha256(corpus_path),
        "recognizer": corpus["recognizer"],
        "baseline": baseline["summary"]["selected"],
        "production": production,
        "targeted_failures": len(targeted),
        "targeted_full_exact_fixed": sum(
            targeted_candidates.get(_key(record), {})
            .get("metrics", {})
            .get("full_exact", False)
            for record in targeted
        ),
        "targeted_component_exact": sum(
            bool(candidate["metrics"]["facts"])
            and all(fact["exact"] for fact in candidate["metrics"]["facts"])
            for candidate in targeted_candidates.values()
        ),
        "baseline_exact_equations": len(baseline_exact),
        "heldout_exact_controls": len(controls),
        "unaffected_exact_equations": len(baseline_exact) - len(controls),
        "production_geometry_verified": sum(
            record["geometry"] is not None
            and record["geometry"]["crop_path_verified"]
            for record in candidates
            if record["production_eligible"]
        ),
        "heldout_exact_control_regressions": sum(
            not record["metrics"]["full_exact"] for record in controls
        ),
        "high_dpi_scan_diagnostic": {
            "source": diagnostic["source"],
            "page": diagnostic["page"],
            "full_exact": diagnostic["metrics"]["full_exact"],
            "production_eligible": False,
            "reason": "whole-page VLM output does not retain a separate equation region",
        },
        "candidates": candidates,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=_DEFAULT_CORPUS)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    report = evaluate(args.corpus.resolve())
    print(
        "equation recovery: "
        f"{report['baseline']['full_exact']}/12 -> {report['production']['full_exact']}/12 "
        f"full exact; {report['targeted_component_exact']}/4 targeted component exact; "
        f"{report['heldout_exact_control_regressions']} held-out regressions"
    )
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n")
    if args.check:
        expected = json.loads(args.corpus.read_text())["expected"]
        observed = {key: report[key] for key in expected}
        if observed != expected:
            raise SystemExit(f"equation recovery mismatch: {observed} != {expected}")


if __name__ == "__main__":
    main()
